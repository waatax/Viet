// Tokenize preserving hyphenated Vietnamese words like "ghi-ta" and apostrophes in English
const TOKEN_RE = /[A-Za-zÀ-ỹđĐ]+(?:[-'][A-Za-zÀ-ỹđĐ]+)*/g;

export function tokenizeLyric(text) {
  const tokens = [];
  TOKEN_RE.lastIndex = 0;
  let m;
  while ((m = TOKEN_RE.exec(text)) !== null) {
    tokens.push({
      text: m[0],
      lower: m[0].normalize('NFC').toLowerCase(),
      start: m.index,
      end: m.index + m[0].length
    });
  }
  return tokens;
}

function isSpaceOnly(text, start, end) {
  return /^[ \t]+$/.test(text.slice(start, end));
}

function makeSegment({ text, zh, pos, kind, hanViet = '', start = -1, end = -1 }) {
  const isEn = kind === 'en';
  const tones = isEn ? [] : analyzeVietnameseTones(text.replace(/-/g, ' '));
  return {
    text,
    zh,
    pos: pos || (kind === 'phrase' ? '片語' : ''),
    kind, // 'phrase' | 'word' | 'en'
    hanViet: hanViet || '',
    tones,
    start,
    end
  };
}

/**
 * Segments a single Vietnamese lyric line into ordered, verified word & phrase units,
 * plus inline spans for rendering subtle phrase underlines right inside the Vietnamese lyric line.
 */
export function segmentLyricLine(lineVi, fallbackDict = null) {
  const text = String(lineVi || '').normalize('NFC').trim();
  if (!text) return { segments: [], inlineRuns: [] };

  // 1. Check exact line override first
  const override = LINE_SEGMENT_OVERRIDES[text];
  if (override) {
    const segments = [];
    let cursor = 0;
    const inlineRuns = [];
    for (const [segText, zh, pos, kind, hv = ''] of override) {
      const idx = text.indexOf(segText, cursor);
      if (idx > cursor) {
        inlineRuns.push({ text: text.slice(cursor, idx), kind: 'plain' });
      }
      const start = idx >= 0 ? idx : cursor;
      const end = idx >= 0 ? idx + segText.length : cursor;
      if (idx >= 0) {
        inlineRuns.push({ text: segText, kind });
        cursor = end;
      }
      segments.push(makeSegment({ text: segText, zh, pos, kind, hanViet: hv, start, end }));
    }
    if (cursor < text.length) {
      inlineRuns.push({ text: text.slice(cursor), kind: 'plain' });
    }
    return { segments, inlineRuns };
  }

  // 2. Greedy longest-match against curated SONG_PHRASES (4 -> 3 -> 2 words), then SONG_WORDS, then fallback single-word dict
  const tokens = tokenizeLyric(text);
  const segments = [];
  const inlineRuns = [];
  let cursor = 0;
  let i = 0;

  while (i < tokens.length) {
    let matched = null;

    // Try curated multi-word phrases (up to 4 tokens, space-separated only)
    for (let len = Math.min(4, tokens.length - i); len >= 2; len--) {
      let contiguous = true;
      for (let k = i; k < i + len - 1; k++) {
        if (!isSpaceOnly(text, tokens[k].end, tokens[k + 1].start)) {
          contiguous = false;
          break;
        }
      }
      if (!contiguous) continue;

      const phraseKey = tokens.slice(i, i + len).map((t) => t.lower).join(' ');
      const entry = SONG_PHRASES[phraseKey];
      if (entry) {
        const [zh, pos, hv = '', isEn = false] = entry;
        const start = tokens[i].start;
        const end = tokens[i + len - 1].end;
        matched = {
          len,
          seg: makeSegment({
            text: text.slice(start, end),
            zh,
            pos,
            kind: isEn ? 'en' : 'phrase',
            hanViet: hv,
            start,
            end
          })
        };
        break;
      }
    }

    // Single token lookup
    if (!matched) {
      const tok = tokens[i];
      const curated = SONG_WORDS[tok.lower];
      if (curated) {
        const [zh, pos, hv = '', isEn = false] = curated;
        matched = {
          len: 1,
          seg: makeSegment({
            text: tok.text,
            zh,
            pos,
            kind: isEn ? 'en' : 'word',
            hanViet: hv,
            start: tok.start,
            end: tok.end
          })
        };
      } else if (fallbackDict && fallbackDict[tok.lower]) {
        const d = decodeDictEntry(fallbackDict[tok.lower]);
        matched = {
          len: 1,
          seg: makeSegment({
            text: tok.text,
            zh: d?.zh || '',
            pos: d?.posFull || '',
            kind: 'word',
            hanViet: d?.hanViet || '',
            start: tok.start,
            end: tok.end
          })
        };
      } else {
        matched = {
          len: 1,
          seg: makeSegment({
            text: tok.text,
            zh: '',
            pos: '',
            kind: 'word',
            hanViet: '',
            start: tok.start,
            end: tok.end
          })
        };
      }
    }

    const { seg, len } = matched;
    if (seg.start > cursor) {
      inlineRuns.push({ text: text.slice(cursor, seg.start), kind: 'plain' });
    }
    inlineRuns.push({ text: seg.text, kind: seg.kind });
    cursor = seg.end;
    segments.push(seg);
    i += len;
  }

  if (cursor < text.length) {
    inlineRuns.push({ text: text.slice(cursor), kind: 'plain' });
  }

  return { segments, inlineRuns };
}

